//! Capture installed Firefox and its package dependencies as immutable inputs.
//! No browser, installer or acquired program executes during this capture.
#[path = "support/qemu_build.rs"]
#[allow(dead_code)]
mod qemu_build;
use anyhow::{ensure, Context, Result};
use md_sim_runtime::{
    isolation::save_json,
    store::{hash_file, Store},
};
use serde_json::json;
use std::{
    collections::{BTreeMap, BTreeSet},
    fs,
    io::Read,
    os::unix::fs::PermissionsExt,
    path::{Component, Path},
};

fn main() -> Result<()> {
    let args: Vec<_> = std::env::args_os().collect();
    ensure!(
        (2..=4).contains(&args.len()) && args.get(3).is_none_or(|arg| arg == "--strace"),
        "usage: capture_browser NEW_DIRECTORY [EXISTING_STORE [--strace]]"
    );
    let directory = Path::new(&args[1]);
    ensure!(!directory.try_exists()?, "capture output must be new");
    fs::create_dir_all(directory)?;
    let trace = args.get(3).is_some();
    let mut package_names = BTreeSet::from(["firefox", "nss", "ttf-liberation"]);
    if trace {
        package_names.insert("strace");
    }
    let packages = qemu_build::package_closure(&package_names)?;
    let mut members = BTreeSet::new();
    let mut records = Vec::new();
    for (name, (root, description)) in packages {
        let files = fs::read_to_string(root.join("files"))?;
        ensure!(files.len() <= 2 * 1024 * 1024, "package member budget");
        for line in files
            .lines()
            .skip_while(|l| *l != "%FILES%")
            .skip(1)
            .take_while(|l| !l.starts_with('%'))
        {
            // Browser runtime files only. Exclude package documentation,
            // development headers and locale catalogues. Firefox's own assets
            // remain complete under /usr/lib/firefox.
            let runtime_library = line.starts_with("usr/lib/")
                && !line.ends_with(".a")
                && !line.ends_with(".la")
                && !line.ends_with(".pc")
                && !line.starts_with("usr/lib/python")
                && !line.starts_with("usr/lib/cmake/")
                && !line.starts_with("usr/lib/pkgconfig/");
            if runtime_library
                || line.starts_with("usr/share/fonts/liberation/")
                || line.starts_with("usr/share/fontconfig/")
                || line.starts_with("usr/share/glib-2.0/schemas/")
                || line.starts_with("usr/share/mime/")
                || line.starts_with("etc/fonts/")
                || ["usr/bin/certutil", "usr/bin/pk12util"].contains(&line)
                || (trace && line == "usr/bin/strace")
            {
                ensure!(
                    Path::new(line)
                        .components()
                        .all(|c| matches!(c, Component::Normal(_))),
                    "package path escape"
                );
                members.insert(line.to_string());
            }
        }
        records.push(json!({"name":name,"description":description,"desc":hash_file(&root.join("desc"))?,"files":hash_file(&root.join("files"))?}));
    }
    // These installed caches are generated by package hooks and therefore
    // absent from package member lists. Capture their exact observed bytes.
    // Do not rebuild them or infer the browser works because they are present.
    let generated_caches = [
        "usr/share/glib-2.0/schemas/gschemas.compiled",
        "usr/share/mime/mime.cache",
        "usr/lib/gtk-3.0/3.0.0/immodules.cache",
        "usr/lib/gdk-pixbuf-2.0/2.10.0/loaders.cache",
    ];
    members.extend(generated_caches.iter().map(|path| (*path).to_owned()));
    let mut entries = Vec::new();
    let mut total = 0u64;
    let store_root = args
        .get(2)
        .map(std::path::PathBuf::from)
        .unwrap_or_else(|| directory.join("input-store"));
    let store = Store::open(&store_root, 512 * 1024 * 1024)?;
    let mut captured = BTreeMap::new();
    let mut links = BTreeMap::new();
    let mut excluded = Vec::new();
    let mut link_directories = BTreeSet::new();
    let mut visited = BTreeSet::new();
    while let Some(relative) = members.pop_first() {
        if !visited.insert(relative.clone()) {
            continue;
        }
        let path = Path::new("/").join(&relative);
        let metadata =
            fs::symlink_metadata(&path).with_context(|| format!("inspect {}", path.display()))?;
        if path == Path::new("/usr/lib/firefox/libonnxruntime.so")
            && metadata.is_symlink()
            && !path.exists()
        {
            excluded.push(json!({"path":path,"reason":"Installed Firefox lists onnxruntime as optional for local machine learning; its target is absent. No local machine learning browser capability is claimed.","link":fs::read_link(&path)?}));
            continue;
        }
        if metadata.is_file() && metadata.permissions().mode() & 0o6000 != 0 {
            excluded.push(json!({"path":path,"reason":"Privileged system helper is outside the unprivileged browser closure","mode":metadata.permissions().mode() & 0o7777}));
            continue;
        }
        if metadata.is_file() {
            total += metadata.len();
        }
        ensure!(
            total <= 1024 * 1024 * 1024 && entries.len() < 60_000,
            "browser payload capture budget"
        );
        ensure!(
            metadata.is_dir() || metadata.is_file() || metadata.is_symlink(),
            "special browser input"
        );
        entries.push(json!({"path":path,"size":metadata.len(),"kind":if metadata.is_dir(){"directory"}else if metadata.is_symlink(){"symlink"}else{"file"}}));
        if metadata.is_file() {
            let source = path
                .canonicalize()
                .with_context(|| format!("resolve {}", path.display()))?;
            ensure!(
                source.starts_with("/usr") || source.starts_with("/etc/fonts"),
                "browser source escaped declared roots"
            );
            let object = hash_file(&source)?;
            ensure!(
                object.size == metadata.len(),
                "browser source size changed during capture"
            );
            store.import(&source, &object)?;
            let saved = store.verified_path(&object)?.canonicalize()?;
            let mut magic = [0u8; 4];
            let elf = fs::File::open(&saved)?.read(&mut magic)? == 4 && &magic == b"\x7fELF";
            captured.insert(
                path.to_string_lossy().into_owned(),
                json!({"source":saved,"object":object,
                "mode":if elf || metadata.permissions().mode() & 0o111 != 0 {0o555} else {0o444}}),
            );
        } else if metadata.is_symlink() {
            let target = fs::read_link(&path)?;
            let resolved = path
                .canonicalize()
                .with_context(|| format!("resolve link {}", path.display()))?;
            ensure!(
                resolved.starts_with("/usr") || resolved.starts_with("/etc/fonts"),
                "browser link escaped declared roots"
            );
            // A package link may point through another directory link. Keep
            // the original target as evidence, but use a checked final path
            // in this derived tool payload. Never write members through links.
            entries.last_mut().context("link inventory entry absent")?["original_target"] =
                json!(target);
            entries.last_mut().context("link inventory entry absent")?["derived_target"] =
                json!(resolved);
            members.insert(resolved.strip_prefix("/")?.to_string_lossy().into_owned());
            if resolved.is_dir() {
                let mut directories = vec![resolved.clone()];
                while let Some(directory) = directories.pop() {
                    if !link_directories.insert(directory.clone()) {
                        continue;
                    }
                    for entry in fs::read_dir(&directory)? {
                        let entry = entry?;
                        let child = entry.path();
                        ensure!(
                            child.components().count() <= 256
                                && members.len() + visited.len() < 8192,
                            "linked directory closure exceeds bound"
                        );
                        members.insert(child.strip_prefix("/")?.to_string_lossy().into_owned());
                        if entry.file_type()?.is_dir() {
                            directories.push(child);
                        }
                    }
                }
            }
            links.insert(
                path.to_string_lossy().into_owned(),
                resolved.to_string_lossy().into_owned(),
            );
        }
    }
    save_json(
        &directory.join("inventory.json"),
        &json!({"schema":"md-sim-browser-package-inventory/1","packages":records,"files":entries,"excluded":excluded,"generated_installed_caches":generated_caches,"syscall_trace_tool":trace,
        "file_bytes":total,"scope":"Captured installed package runtime subset; excludes static libraries, development metadata, Python modules, privileged helpers and fonts outside Liberation. Available Firefox runtime assets retained; absent optional ONNX link recorded separately. Symlink targets normalized to checked absolute canonical paths with original targets retained. File bytes unchanged. Actual isolated browser execution still required."}),
    )?;
    save_json(
        &directory.join("payload.json"),
        &json!({"schema":"md-sim-vm-payload/1","files":captured,"symlinks":links}),
    )?;
    save_json(
        &directory.join("capture.json"),
        &json!({"schema":"md-sim-browser-capture/1",
        "recipe":hash_file(&std::env::current_exe()?)?,"recipe_source":md_sim_firmware::prepare::hash_bytes(include_bytes!("capture_browser.rs")),
        "payload":hash_file(&directory.join("payload.json"))?,"inventory":hash_file(&directory.join("inventory.json"))?,"file_bytes":total,
        "provenance":"Observed installed Firefox157.0.1 package and selected runtime package files. Not a browser source build or package signature authentication claim."}),
    )?;
    println!(
        "{}",
        json!({"file_bytes":total,"payload":directory.join("payload.json"),"captured":true,"actual_browser_pass":false})
    );
    Ok(())
}
